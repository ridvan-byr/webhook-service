using System.Security.Claims;
using System.Security.Cryptography;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Options;
using WebhookService.Api.Contracts;
using WebhookService.Api.Security;
using WebhookService.Core.Security;
using WebhookService.Infrastructure.Persistence;
using WebhookService.Infrastructure.Security;
using DomainEndpoint = WebhookService.Core.Domain.Endpoint;

namespace WebhookService.Api.Routes;

internal static class EndpointRoutes
{
    public static void MapEndpointRoutes(this IEndpointRouteBuilder app)
    {
        var group = app.MapGroup("/endpoints").WithTags("Endpoints");

        group.MapPost("/", CreateAsync).WithName("CreateEndpoint");
        group.MapGet("/", ListAsync).WithName("ListEndpoints");
        group.MapGet("/{id:guid}", GetAsync).WithName("GetEndpoint");
    }

    private static async Task<IResult> CreateAsync(
        ClaimsPrincipal user,
        CreateEndpointRequest body,
        WebhookDbContext db,
        TimeProvider time,
        IOptions<NetworkSecurityOptions> security,
        CancellationToken ct)
    {
        // An early, readable error for obviously wrong URLs. The real protection against reaching
        // internal networks is the check made when the worker connects (SafeConnector).
        var (url, error) = EndpointUrlValidator.Validate(
            body.Url, security.Value.RequireHttps, security.Value.AllowPrivateNetworks);

        if (url is null)
        {
            return Results.ValidationProblem(new Dictionary<string, string[]>
            {
                ["url"] = [error!],
            });
        }

        // Generated by the server so it is always long and random. Shown once, in this response.
        var secret = "whsec_" + Convert.ToBase64String(RandomNumberGenerator.GetBytes(32));

        var endpoint = DomainEndpoint.Create(user.TenantId(), url, secret, time.GetUtcNow());
        db.Endpoints.Add(endpoint);
        await db.SaveChangesAsync(ct);

        return Results.Created(
            $"/endpoints/{endpoint.Id}",
            new CreatedEndpointResponse(
                endpoint.Id, endpoint.Url.ToString(), endpoint.IsActive, endpoint.CreatedAt, secret));
    }

    private static async Task<IResult> ListAsync(ClaimsPrincipal user, WebhookDbContext db, CancellationToken ct)
    {
        var tenantId = user.TenantId();

        var endpoints = await db.Endpoints.AsNoTracking()
            .Where(e => e.TenantId == tenantId)
            .OrderBy(e => e.CreatedAt)
            .ToListAsync(ct);

        return Results.Ok(endpoints.Select(ToResponse));
    }

    private static async Task<IResult> GetAsync(
        Guid id,
        ClaimsPrincipal user,
        WebhookDbContext db,
        CancellationToken ct)
    {
        var tenantId = user.TenantId();

        // Filtering by tenant means another tenant's endpoint looks like it does not exist.
        var endpoint = await db.Endpoints.AsNoTracking()
            .SingleOrDefaultAsync(e => e.Id == id && e.TenantId == tenantId, ct);

        return endpoint is null ? Results.NotFound() : Results.Ok(ToResponse(endpoint));
    }

    private static EndpointResponse ToResponse(DomainEndpoint e) =>
        new(e.Id, e.Url.ToString(), e.IsActive, e.CreatedAt);
}
